/**
 * Reads src/index.css and writes src/theme-lab/tokens.generated.ts:
 *   - PRIMITIVES: every hex colour in the palette, with family and shade
 *   - ROLES:      the semantic colour roles the vendored components actually
 *                 reference, each with the primitive its dark value points at
 *
 * Run with: npm run generate:tokens
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs'
import { join } from 'node:path'

const css = readFileSync('src/index.css', 'utf8')
const theme = css.slice(css.indexOf('@theme {'), css.indexOf('@property'))
// The shadcn bridge (`@theme inline` at the end of the file) maps shadcn role
// names onto zSpace ones, so `bg-card` renders `--color-bg-surface-form`.
// Those zSpace roles belong in the rail even though no component names them.
const bridge = css.slice(css.indexOf('@theme inline'))

const decls = [...theme.matchAll(/^\s*(--[a-z0-9-]+):\s*([^;]+);/gm)].map(
  ([, name, value]) => ({ name, value: value.trim() })
)

// --- palette: every literal colour, including the overlays
const primitives = decls
  .filter((d) => /^--(color|overlay)-/.test(d.name) && d.value.startsWith('#'))
  .map((d) => {
    const bare = d.name.replace(/^--(color|overlay)-/, '')
    const m = bare.match(/^(.*?)-(\d+|white|black|subtle|default|light|medium|heavy|strong)$/)
    return {
      name: d.name,
      hex: d.value,
      family: m ? m[1] : bare,
      shade: m ? m[2] : '',
      isOverlay: d.name.startsWith('--overlay-'),
    }
  })

// --- which roles do the vendored components reference?
const UTILITY = /\b(?:bg|text|border|ring|shadow|fill|stroke|from|to|via|decoration|outline|caret|accent|divide)-((?:bg|content|border|special|icon|overlay)-[a-z0-9-]+)/g
const used = new Set()
const walk = (dir) => {
  for (const entry of readdirSync(dir)) {
    const p = join(dir, entry)
    if (statSync(p).isDirectory()) walk(p)
    else if (/\.tsx?$/.test(p) && !p.includes('tokens.generated')) {
      const src = readFileSync(p, 'utf8')
      for (const [, role] of src.matchAll(UTILITY)) used.add('--color-' + role)
    }
  }
}
walk('src')

for (const [, role] of bridge.matchAll(/var\((--color-(?:bg|content|border|special|icon)-[a-z0-9-]+)\)/g)) {
  used.add(role)
}

const byName = new Map(decls.map((d) => [d.name, d.value]))
/** Follows `var(--x)` chains down to the primitive that actually holds the hex. */
const resolve = (value, depth = 0) => {
  const m = value.match(/^var\((--[a-z0-9-]+)\)$/)
  if (!m || depth > 5) return value
  const next = byName.get(m[1])
  return next ? resolve(next, depth + 1) : m[1]
}

const roles = decls
  .filter((d) => used.has(d.name) && d.value.includes('var('))
  .map((d) => {
    const ref = d.value.match(/var\((--[a-z0-9-]+)\)/)?.[1] ?? null
    return {
      name: d.name,
      // bg / content / border / icon / special — the rail's grouping
      group: d.name.replace('--color-', '').split('-')[0],
      darkRef: ref,
      darkHex: resolve(d.value),
    }
  })
  .sort((a, b) => a.name.localeCompare(b.name))

const out = `// GENERATED by scripts/generate-theme-tokens.mjs — do not edit.
// Regenerate after changing the palette or roles in src/index.css:
//   npm run generate:tokens

export type Primitive = {
  name: string
  hex: string
  family: string
  shade: string
  isOverlay: boolean
}

export type Role = {
  name: string
  group: string
  /** The palette entry the locked dark value points at. */
  darkRef: string | null
  darkHex: string
}

export const PRIMITIVES: Primitive[] = ${JSON.stringify(primitives, null, 2)}

export const ROLES: Role[] = ${JSON.stringify(roles, null, 2)}
`

writeFileSync('src/theme-lab/tokens.generated.ts', out)
console.log(`primitives: ${primitives.length}`)
console.log(`roles:      ${roles.length}`)
